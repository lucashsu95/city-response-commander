import { useEffect, useState } from 'react';

interface BuildMetadata {
  branch: string;
  commit: string;
  region: string;
  buildTime: string;
}

const SAFE_FALLBACK: BuildMetadata = {
  branch: '64/demo-live-mvp',
  commit: 'local',
  region: 'us-west-2',
  buildTime: 'local build',
};

const ALLOWED_KEYS = [
  'VITE_APP_BRANCH',
  'VITE_APP_COMMIT',
  'VITE_AWS_REGION',
  'VITE_BUILD_TIME',
] as const;

function readBuildMetadata(): BuildMetadata {
  const source = (import.meta as unknown as { env: Record<string, string | undefined> }).env;
  const raw: Record<string, string | undefined> = {};
  for (const key of ALLOWED_KEYS) {
    raw[key] = source[key];
  }
  return {
    branch:
      raw.VITE_APP_BRANCH && raw.VITE_APP_BRANCH.length > 0
        ? raw.VITE_APP_BRANCH
        : SAFE_FALLBACK.branch,
    commit:
      raw.VITE_APP_COMMIT && raw.VITE_APP_COMMIT.length > 0
        ? raw.VITE_APP_COMMIT
        : SAFE_FALLBACK.commit,
    region:
      raw.VITE_AWS_REGION && raw.VITE_AWS_REGION.length > 0
        ? raw.VITE_AWS_REGION
        : SAFE_FALLBACK.region,
    buildTime:
      raw.VITE_BUILD_TIME && raw.VITE_BUILD_TIME.length > 0
        ? raw.VITE_BUILD_TIME
        : SAFE_FALLBACK.buildTime,
  };
}

