export function App(): JSX.Element {
  const [metadata] = useState<BuildMetadata>(() => readBuildMetadata());
  const [clock, setClock] = useState<string>(() => new Date().toISOString());

  useEffect(() => {
    const interval = window.setInterval(() => {
      setClock(new Date().toISOString());
    }, 1000);
    return () => window.clearInterval(interval);
  }, []);

  return (
    <div className="app">
      <Header metadata={metadata} />
      <main className="app-main">
        <MetaPanel metadata={metadata} />
        <FeatureGrid />
      </main>
      <div className="app-clock" aria-label="Live clock">
        Live clock (UTC):&nbsp;<code>{clock}</code>
      </div>
      <Footer />
    </div>
  );
}
