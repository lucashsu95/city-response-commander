/**
 * Unified Adaptive Reasoning Engine (UARE) — deterministic decision logic
 * for the "SOP type coverage gap" case (spec: `.kiro/specs/unified-adaptive-
 * reasoning-engine/`, design.md §3–§5).
 *
 * When an injected incident triggers none of `article1`–`article6`
 * (`triggered_articles` is empty), the existing recommendation prompt
 * (`packages/ai-generator/src/recommendation-generator.ts`) is left with
 * "觸發 SOP 條款: 無" and an instruction not to fabricate — a dead end that
 * pushes the LLM toward refusal or hallucination. This module gives that
 * situation a deterministic, real-data-grounded fallback:
 *
 * - `resolveSopMatch` turns the existing `triggered_articles` output into an
 *   explicit boolean judgment (R1).
 * - `UNIVERSAL_DEFENSE_PRINCIPLES` is a fixed, non-official principle set
 *   (R2) — explicitly NOT a new SOP article.
 * - `selectGroundingCandidates` grounds "peripheral guidance" in real,
 *   currently-low-congestion road segments from the official road network
 *   (R3, R6, R7) — never a fabricated road name.
 *
 * @module domain/rule_engine/universal_defense
 */

import type {
  GroundingCandidate,
  SopMatchResult,
  UniversalPrinciple,
} from '@city-commander/shared-schemas';
import type { RoadNetworkModel } from '../road_network/road_network_model.js';
import { classifySegments } from './classification_engine.js';
import { CAPACITY_THRESHOLD } from './article2.js';

// ─── Requirement 1: SOP match judgment ────────────────────────────────────

/**
 * Determine SOP coverage status from the existing `triggered_articles`
 * output. Pure projection — does not evaluate any trigger condition itself.
 *
 * @param triggeredArticles - `articles.triggered_articles` from `aggregateArticles`
 */
export function resolveSopMatch(triggeredArticles: readonly number[]): SopMatchResult {
  const matched = triggeredArticles.length > 0;
  return {
    sop_matched: matched,
    sop_authority: matched ? 'OFFICIAL_SOP' : 'SYSTEM_DEFAULT_PRINCIPLE',
  };
}

